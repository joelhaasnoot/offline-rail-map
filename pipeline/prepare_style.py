"""Turn the generated OpenRailwayMap style + legend + sprites + fonts into Android app assets.

Reads (from the pipeline work dir, see build-sprites.sh):
  work/style.json                        generated with `node proxy/js/styles.mjs`
  work/legend.json                       generated with `node proxy/js/legend.mjs`
  work/sprites/{sprite,sdf_sprite}_*     generated by Martin from the symbols/ directory
  work/OpenRailwayMap-vector/proxy/font  glyph PBFs

Writes (to android/app/src/main/assets):
  style/orm-style.json   sources point at the {{ORM_TILES}} placeholder, sprite/glyphs to asset://
  style/legend.json      one key per app view
  sprites/symbols*.json|png   default + SDF sprite sheets merged (SDF icons prefixed with "sdf:")
  font/...
"""
import json
import os
import re
import shutil
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = os.path.join(ROOT, "pipeline", "work")
ASSETS = os.path.join(ROOT, "android", "app", "src", "main", "assets")

DROP_SOURCES = {"openhistoricalmap", "dem"}
ATTRIBUTION = '<a href="https://www.openstreetmap.org/copyright">© OpenStreetMap contributors</a> · <a href="https://openrailwaymap.app">OpenRailwayMap</a>'


# --- MapLibre Native compatibility -------------------------------------------------------------
# The upstream style targets MapLibre GL JS. MapLibre Native lacks a few features; patch them here.

DATA_OPS = {"get", "has", "feature-state", "properties", "id", "geometry-type"}


def is_data_driven(e):
    if isinstance(e, list):
        if e and isinstance(e[0], str) and e[0] in DATA_OPS:
            return True
        return any(is_data_driven(x) for x in e)
    return False


HSL_SPACE = re.compile(r"hsla?\(\s*([-\d.]+)(deg)?\s+([-\d.]+%)\s+([-\d.]+%)\s*(?:/\s*([-\d.]+%?))?\s*\)")


def fix_colors(e):
    """MapLibre Native only understands comma-separated hsl(); rewrite CSS Color 4 space syntax."""
    if isinstance(e, str):
        def repl(m):
            h, _, s, l, a = m.groups()
            if a is None:
                return f"hsl({h}, {s}, {l})"
            return f"hsla({h}, {s}, {l}, {a})"
        return HSL_SPACE.sub(repl, e)
    if isinstance(e, list):
        return [fix_colors(x) for x in e]
    if isinstance(e, dict):
        return {k: fix_colors(v) for k, v in e.items()}
    return e


def replace_op(e, old, new):
    """Recursively rename expression operator `old` to `new`."""
    if isinstance(e, list):
        out = [replace_op(x, old, new) for x in e]
        if out and out[0] == old:
            out[0] = new
        return out
    if isinstance(e, dict):
        return {k: replace_op(v, old, new) for k, v in e.items()}
    return e


def and_filter(existing, extra):
    if existing is None:
        return extra
    return ["all", existing, extra]


def split_data_driven(layer, prop):
    """Native cannot evaluate per-feature values for `prop` (e.g. line-dasharray, text-font).

    Split the layer into one layer per branch of a `match`/single-condition `case` expression,
    adding the branch condition to the layer filter. Returns a list of layers.
    """
    section = "paint" if prop in layer.get("paint", {}) else "layout"
    expr = layer[section][prop]
    if not is_data_driven(expr):
        return [layer]
    base_filter = layer.get("filter")

    def clone(suffix, value, extra_filter):
        copy = json.loads(json.dumps(layer))
        copy["id"] = f"{layer['id']}__{suffix}"
        copy[section][prop] = value
        copy["filter"] = and_filter(base_filter, extra_filter)
        return copy

    if expr[0] == "match" and isinstance(expr[1], list) and expr[1][0] == "get" and not is_data_driven(expr[2:]):
        key = expr[1][1]
        branches = expr[2:-1]
        fallback = expr[-1]
        result = []
        all_labels = []
        for i in range(0, len(branches), 2):
            labels = branches[i] if isinstance(branches[i], list) else [branches[i]]
            all_labels.extend(labels)
            result.append(clone(f"m{i // 2}", branches[i + 1], ["in", ["get", key], ["literal", labels]]))
        result.append(clone("mf", fallback, ["!", ["in", ["get", key], ["literal", all_labels]]]))
        return result
    if expr[0] == "case" and len(expr) == 4 and not is_data_driven(expr[2:]):
        return [clone("c1", expr[2], expr[1]), clone("c0", expr[3], ["!", expr[1]])]
    print(f"WARNING: cannot split {prop} of layer {layer['id']}, using fallback value: {json.dumps(expr)[:120]}")
    layer[section][prop] = expr[-1]
    return [layer]


def patch_for_native(style):
    style["layers"] = fix_colors(replace_op(style["layers"], "interpolate-hcl", "interpolate"))
    layers = []
    for layer in style["layers"]:
        layout = layer.get("layout", {})
        if "icon-overlap" in layout:
            layout["icon-allow-overlap"] = layout.pop("icon-overlap") == "always"
        if "text-overlap" in layout:
            layout["text-allow-overlap"] = layout.pop("text-overlap") == "always"
        expanded = [layer]
        for prop in ("line-dasharray", "text-font"):
            expanded = [x for l in expanded for x in split_data_driven(l, prop)] if any(
                prop in l.get("paint", {}) or prop in l.get("layout", {}) for l in expanded) else expanded
        layers.extend(expanded)
    print(f"native patch: {len(style['layers'])} -> {len(layers)} layers")
    style["layers"] = layers


def add_signal_track_numbers(style):
    """Show track numbers (track_ref) in the Train protection view too, not only in Infrastructure.

    Upstream gates the track number layer on `stations == "station"`. Rather than widen that layer,
    add a copy for `tracks == "train_protection"` beneath the point-of-interest and signal layers: symbols are placed top
    layer first, so signal icons and their labels claim their space and the track numbers fill the
    gaps along the line instead of covering them. Closer label spacing gives each track more
    candidate spots between the signals of a busy station throat.
    """
    layers = style["layers"]
    ids = [l["id"] for l in layers]
    if "railway_text_track_numbers" not in ids or "railway_symbols_outline_outline" not in ids:
        print("WARNING: track number or signal layers not found, track numbers stay Infrastructure-only")
        return
    original = layers[ids.index("railway_text_track_numbers")]
    copy = json.loads(json.dumps(original))
    copy["id"] = "railway_text_track_numbers_train_protection"
    copy["layout"]["visibility"] = [
        "case", ["<", ["global-state", "date"], 2026], "none",
        ["==", ["global-state", "tracks"], "train_protection"], "visible", "none",
    ]
    copy["layout"]["symbol-spacing"] = 150
    layers.insert(ids.index("railway_symbols_outline_outline"), copy)


# --- Crossing tracks ----------------------------------------------------------------------------
# Where tracks cross at different heights the map should show which one is on top.

UPPER_LAYER = 2  # OSM `layer` from which a bridge is drawn as the upper deck


def outer_width(width, gap):
    """Total width of a line drawn with line-width `width` and line-gap-width `gap`."""
    if isinstance(width, (int, float)):
        return gap + 2 * width
    if width[0] != "interpolate" or width[2] != ["zoom"]:
        sys.exit(f"cannot widen line-width {json.dumps(width)[:120]}")
    stops = width[3:]
    out = width[:3]
    for i in range(0, len(stops), 2):
        out += [stops[i], ["+", gap, ["*", 2, stops[i + 1]]]]
    return out


def bridge_levels(layers):
    """Make bridges hide what passes under them.

    Upstream draws a bridge as a railing and a casing, both hollow lines either side of the track, so
    the tracks underneath show straight through it, and two bridges crossing (one on OSM layer 1, the
    other on layer 2) look the same whichever is on top. Here every bridge gets a solid mask in the
    casing colour under its railing, which interrupts the tracks and platforms below it, and the
    bridges of `layer` >= UPPER_LAYER are drawn in a second pass (mask, railing, casing, fill) over
    the lower ones. Tiles without `layer` (packs built before it was added) draw everything in the
    first pass.
    """
    idx = [i for i, l in enumerate(layers) if "_bridge_" in l["id"]]
    first, last = idx[0], idx[-1]
    if idx != list(range(first, last + 1)):
        sys.exit("bridge layers are not one block")
    block = layers[first:last + 1]
    by_id = {l["id"]: l for l in block}
    level = ["coalesce", ["get", "layer"], 0]

    def at_level(layer, condition, suffix):
        copy = json.loads(json.dumps(layer))
        copy["id"] += suffix
        copy["filter"] = and_filter(layer.get("filter"), condition)
        return copy

    def mask(railing, condition, suffix):
        casing = by_id[railing["id"].replace("_bridge_railing", "_bridge_casing")]
        copy = at_level(railing, condition, suffix)
        copy["id"] = railing["id"].replace("_bridge_railing", "_bridge_mask") + suffix
        copy["layout"]["line-cap"] = "butt"
        copy["paint"] = {
            "line-color": casing["paint"]["line-color"],
            "line-width": outer_width(railing["paint"]["line-width"], railing["paint"]["line-gap-width"]),
        }
        return copy

    high = [l for l in block if l.get("source-layer") == "railway_line_high"]
    railings = [l for l in high if l["id"].endswith("_bridge_railing")]
    passes = []
    for condition, suffix, members in (
        (["<", level, UPPER_LAYER], "", block),
        ([">=", level, UPPER_LAYER], "__upper", high),
    ):
        passes += [mask(r, condition, suffix) for r in railings]
        passes += [at_level(l, condition, suffix) if l in high else l for l in members]
    print(f"bridge levels: {len(block)} -> {len(passes)} layers")
    return layers[:first] + passes + layers[last + 1:]


def prepare_style():
    style = json.load(open(os.path.join(WORK, "style.json"), encoding="utf-8"))
    before = len(style["layers"])
    style["layers"] = [l for l in style["layers"] if l.get("source") not in DROP_SOURCES]
    for s in DROP_SOURCES:
        style["sources"].pop(s, None)
    for name, src in style["sources"].items():
        if src.get("type") == "vector":
            src["url"] = "{{ORM_TILES}}"
            src.pop("metadata", None)
            src["attribution"] = ATTRIBUTION
    patch_for_native(style)
    add_signal_track_numbers(style)
    style["layers"] = bridge_levels(style["layers"])
    style["sprite"] = "asset://sprites/symbols"
    style["glyphs"] = "asset://font/{fontstack}/{range}.pbf"
    style["name"] = "OpenRailwayMap (offline)"
    # `bearing` defaults to null upstream; it only matters for pitched views, and null breaks
    # numeric expression parsing once substituted, so use 0.
    style.setdefault("state", {}).setdefault("bearing", {})["default"] = 0
    os.makedirs(os.path.join(ASSETS, "style"), exist_ok=True)
    with open(os.path.join(ASSETS, "style", "orm-style.json"), "w", encoding="utf-8") as f:
        json.dump(style, f, separators=(",", ":"), ensure_ascii=False)
    print(f"style: {before} -> {len(style['layers'])} layers, {len(style['sources'])} sources")


def merge_sprites(suffix):
    sdir = os.path.join(WORK, "sprites")
    default_json = json.load(open(os.path.join(sdir, f"sprite_symbols{suffix}.json")))
    sdf_json = json.load(open(os.path.join(sdir, f"sdf_sprite_symbols{suffix}.json")))
    default_png = Image.open(os.path.join(sdir, f"sprite_symbols{suffix}.png")).convert("RGBA")
    sdf_png = Image.open(os.path.join(sdir, f"sdf_sprite_symbols{suffix}.png")).convert("RGBA")

    merged = Image.new("RGBA", (max(default_png.width, sdf_png.width), default_png.height + sdf_png.height))
    merged.paste(default_png, (0, 0))
    merged.paste(sdf_png, (0, default_png.height))

    index = dict(default_json)
    for name, entry in sdf_json.items():
        e = dict(entry)
        e["y"] = e["y"] + default_png.height
        e["sdf"] = True
        index[f"sdf:{name}"] = e

    out = os.path.join(ASSETS, "sprites")
    os.makedirs(out, exist_ok=True)
    merged.save(os.path.join(out, f"symbols{suffix}.png"), optimize=True)
    with open(os.path.join(out, f"symbols{suffix}.json"), "w") as f:
        json.dump(index, f, separators=(",", ":"))
    print(f"sprites{suffix}: {len(index)} icons, {merged.width}x{merged.height}")


# --- Key ----------------------------------------------------------------------------------------
# Upstream's legend.json is one tree for every map configuration: per source layer, sections that
# each apply to some `global-state` (`mapState`; for the list-valued `pois` and `signals` a section
# applies when its value is in the list). The app offers the website's fixed views, so it gets one
# flat key per view instead, in the format it reads: {view: {countries, state, sourceLayers: {name:
# {key, matchKeys, features}}}}.

# What the app's views leave to the user's options. These conditions are kept on the key entries
# (as their `mapState`) for the app to check; every other condition is decided here. The `tracks`
# values are the colourings the app offers in those views.
VIEW_OPTIONS = {
    "electrification": {"tracks": ["voltage_frequency", "maximum_current", "power"]},
    "track": {"tracks": ["gauge", "loading_gauge", "track_class"]},
}
OPTION_KEYS = {"showConstructionInfrastructure", "showProposedInfrastructure", "showAbandonedInfrastructure",
               "showRazedInfrastructure", "stationLowZoomLabel"}
APP_VIEWS = ["standard", "speed", "signals", "electrification", "track", "operator"]  # no route view


def known_styles():
    """The website's views (`knownStyles` in proxy/js/ui.js): view id to {name, style: global-state}."""
    source = open(os.path.join(WORK, "OpenRailwayMap-vector", "proxy", "js", "ui.js"), encoding="utf-8").read()
    literal = re.search(r"^const knownStyles = (\{.*?^\});", source, re.M | re.S)
    if not literal:
        sys.exit("knownStyles not found in ui.js")
    out = subprocess.run(["node", "-e", f"process.stdout.write(JSON.stringify({literal.group(1)}))"],
                         check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def resolve_map_state(map_state, fixed, options):
    """Split a legend `mapState` into (applies, conditions left for the app). `fixed` is the view's
    global state, `options` the values the user can choose for the keys the view leaves open."""
    left = {}
    for key, value in (map_state or {}).items():
        if key in options or key in OPTION_KEYS:
            if key in options and value not in options[key]:
                return False, None
            left[key] = value
        elif key not in fixed:
            sys.exit(f"legend mapState key {key!r} is not in the view's state")
        elif isinstance(fixed[key], list):
            if value not in fixed[key]:
                return False, None
        elif fixed[key] != value:
            return False, None
    return True, left


def flatten_legend(legend, view, fixed):
    options = VIEW_OPTIONS.get(view, {})
    fixed = {k: v for k, v in fixed.items() if k not in options}
    source_layers = {}
    for name, sections in legend["sourceLayers"].items():
        if name.split("-", 1)[0] in DROP_SOURCES:
            continue
        keys, features = set(), []
        for section in sections.values():
            applies, section_left = resolve_map_state(section.get("mapState"), fixed, options)
            if not applies:
                continue
            keyed = bool(section.get("key")) or bool(section.get("matchKeys"))
            if keyed:
                keys.add(json.dumps([section.get("key"), section.get("matchKeys")]))
            for item in section.get("features", []):
                applies, item_left = resolve_map_state(item.get("mapState"), fixed, options)
                if not applies:
                    continue
                item = dict(item)
                item.pop("mapState", None)
                if section_left or item_left:
                    item["mapState"] = {**section_left, **item_left}
                variants = []
                for variant in item.get("variants", []):
                    applies, variant_left = resolve_map_state(variant.get("mapState"), fixed, options)
                    if applies:
                        variant = {k: v for k, v in variant.items() if k != "mapState"}
                        if variant_left:
                            variant["mapState"] = variant_left
                        variants.append(variant)
                if "variants" in item:
                    item["variants"] = variants
                if not keyed:
                    # Shown whenever the source layer is on screen, as upstream does for a section
                    # without a key, also next to keyed sections of the same layer.
                    item["keys"] = []
                features.append(item)
        if len(keys) > 1:
            sys.exit(f"legend {view}: sections of {name} use different keys: {keys}")
        if not features:
            continue
        key, match_keys = json.loads(keys.pop()) if keys else ([], None)
        data = {"key": key, "features": features}
        if match_keys:
            data["matchKeys"] = match_keys
        source_layers[name] = data
    return source_layers


def prepare_legend():
    """The upstream legend (what each colour and symbol means) as one key per app view."""
    legend = json.load(open(os.path.join(WORK, "legend.json"), encoding="utf-8"))
    styles = known_styles()

    def add_localized_name(props):
        # The tile server adds localized_name (the name in the requested language) to stations;
        # the legend samples only carry name, which would leave station samples without text.
        if props and "name" in props and "localized_name" not in props:
            props["localized_name"] = props["name"]

    views = {}
    for view in APP_VIEWS:
        state = styles[view]["style"]
        source_layers = flatten_legend(legend, view, state)
        for data in source_layers.values():
            for item in data["features"]:
                item["properties"] = dict(item.get("properties") or {})
                add_localized_name(item["properties"])
                for variant in item.get("variants", []):
                    if variant.get("properties"):
                        variant["properties"] = dict(variant["properties"])
                        add_localized_name(variant["properties"])
        # `state` is the website's view, which the app's MapMode must match (checked by its tests).
        views[view] = {"countries": legend.get("countries", []), "state": state, "sourceLayers": source_layers}
    os.makedirs(os.path.join(ASSETS, "style"), exist_ok=True)
    with open(os.path.join(ASSETS, "style", "legend.json"), "w", encoding="utf-8") as f:
        json.dump(views, f, separators=(",", ":"), ensure_ascii=False)
    entries = sum(len(d["features"]) for v in views.values() for d in v["sourceLayers"].values())
    print(f"legend: {len(views)} views, {entries} entries")


def copy_fonts():
    src = os.path.join(WORK, "OpenRailwayMap-vector", "proxy", "font")
    dst = os.path.join(ASSETS, "font")
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    print(f"fonts: {sorted(os.listdir(dst))}")


if __name__ == "__main__":
    prepare_style()
    prepare_legend()
    merge_sprites("")
    merge_sprites("@2x")
    copy_fonts()
